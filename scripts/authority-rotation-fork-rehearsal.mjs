// Rehearses the rotation package end to end on a LOCAL anvil fork of Fuji. Nothing
// reaches Fuji: the script refuses to run unless the endpoint is a local anvil node.
// No private key is used or stored: the old key is impersonated (anvil_impersonateAccount)
// and the test Safe owners, backup and buyer are anvil's unlocked dev accounts,
// which sign through the node (eth_sendTransaction / eth_signTypedData_v4).
//
//   anvil --fork-url https://api.avax-test.network/ext/bc/C/rpc &
//   ANVIL_URL=http://127.0.0.1:8545 node scripts/authority-rotation-fork-rehearsal.mjs
//
// It executes, in order: the two sale-close pre-steps, creation of a 2-of-3 test
// Safe through the canonical v1.4.1 factory, and the P0 package generated by
// scripts/authority-rotation-plan.mjs for that Safe and a separate backup. After each
// step it reads the postconditions. The Safe and backup here are fork-only stand-ins
// with the same structure as the owner's; their addresses are not proposals.
import { AbiCoder, Interface, JsonRpcProvider, ZeroAddress, getAddress, keccak256, toBeHex } from "ethers";
import { LEGACY_RELEASE_82B26, LEGACY_SALE_82B26, OLD_AUTHORITY, OPEN_OLD_KEY_SALES, ROLES, SAFE_TX_TYPES, buildRotationPlan, buildSaleCloseSteps, packageStatus, releaseIface, safeTxHash } from "./authority-rotation-plan.mjs";

const URL_ = process.env.ANVIL_URL || "http://127.0.0.1:8545";
const SAFE_L2 = "0x29fcB43b46531BcA003ddC8FCB67FFE91900C762";
const FACTORY = "0x4e1DCf7AD4e460CfD30791CCC4F9c8a4f820ec67";
const FALLBACK = "0xfd0732Dc9E303f09fCEf3a7388Ad10A83459Ec99";
const P0_RELEASE = "0x7Bba0690a43E2FFE9ad553fbDa0451177B7B95B6";
const SALES_SLOT = 3n;

const factoryIface = new Interface(["function createProxyWithNonce(address singleton, bytes initializer, uint256 saltNonce) returns (address proxy)"]);
const safeIface = new Interface([
  "function setup(address[] owners, uint256 threshold, address to, bytes data, address fallbackHandler, address paymentToken, uint256 payment, address paymentReceiver)",
  "function execTransaction(address to, uint256 value, bytes data, uint8 operation, uint256 safeTxGas, uint256 baseGas, uint256 gasPrice, address gasToken, address refundReceiver, bytes signatures) payable returns (bool)",
  "function getTransactionHash(address to, uint256 value, bytes data, uint8 operation, uint256 safeTxGas, uint256 baseGas, uint256 gasPrice, address gasToken, address refundReceiver, uint256 _nonce) view returns (bytes32)",
  "function getOwners() view returns (address[])", "function getThreshold() view returns (uint256)", "function nonce() view returns (uint256)", "function VERSION() view returns (string)",
]);
const saleIface = new Interface([
  "function sales(uint256) view returns (uint256 priceWei, uint256 maxSupply, uint256 sold, uint256 perWalletLimit, uint64 startTime, uint64 endTime, bool paused, bool configured)",
  "function purchase(uint256 tokenId, uint256 qty) payable",
  "function configureSale(uint256 tokenId, uint256 priceWei, uint256 maxSupply, uint256 perWalletLimit, uint64 startTime, uint64 endTime, bool paused)",
  "event SaleConfigured(uint256 indexed tokenId, address indexed artist, uint256 priceWei, uint256 maxSupply, uint256 perWalletLimit, uint64 startTime, uint64 endTime, bool paused)",
]);
const releaseEvents = new Interface([
  "event RoleGranted(bytes32 indexed role, address indexed account, address indexed sender)",
  "event RoleRevoked(bytes32 indexed role, address indexed account, address indexed sender)",
  "function payoutOf(uint256) view returns (address)",
  "function mint(address to, uint256 tokenId, uint256 amount, bytes data)",
]);
const roleName = Object.fromEntries(Object.entries(ROLES).map(([k, v]) => [v, k]));
const coder = AbiCoder.defaultAbiCoder();

const provider = new JsonRpcProvider(URL_, undefined, { staticNetwork: false, cacheTimeout: -1 });

async function send(from, to, data, value = 0n) {
  const hash = await provider.send("eth_sendTransaction", [{ from, to, data, value: toBeHex(value), gas: toBeHex(3_000_000) }]);
  // Raw receipt polling: after evm_revert the chain height goes backwards, which can
  // stall confirmation-based waits that track a cached block number.
  for (let i = 0; i < 120; i += 1) {
    const r = await provider.send("eth_getTransactionReceipt", [hash]);
    if (r) return { hash, status: Number(r.status), gasUsed: BigInt(r.gasUsed).toString(), logs: r.logs.map((l) => ({ ...l, topics: l.topics, data: l.data })) };
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  throw new Error(`No receipt for ${hash} on the local fork.`);
}
async function call(from, to, data, value = 0n) {
  try { return { ok: true, result: await provider.call({ from, to, data, value }) }; } catch (error) {
    const d = error?.data || error?.info?.error?.data || null;
    return { ok: false, revertData: typeof d === "string" ? d.slice(0, 74) : null, reason: String(error?.shortMessage || error?.message || error).slice(0, 120) };
  }
}
const hasRole = async (contract, role, account) => releaseIface.decodeFunctionResult("hasRole", await provider.call({ to: contract, data: releaseIface.encodeFunctionData("hasRole", [ROLES[role], account]) }))[0];
const roleLogs = (logs) => logs.flatMap((l) => { try { const p = releaseEvents.parseLog(l); return p ? [{ event: p.name, role: roleName[p.args.role] || p.args.role, account: getAddress(p.args.account), sender: getAddress(p.args.sender) }] : []; } catch { return []; } });
const saleSlots = (tokenId) => { const base = BigInt(keccak256(coder.encode(["uint256", "uint256"], [tokenId, SALES_SLOT]))); return [0n, 1n, 2n, 3n, 4n].map((i) => base + i); };

const snapshot = () => provider.send("evm_snapshot", []);
const revertTo = (id) => provider.send("evm_revert", [id]);
async function signSafeTx(signer, safe, tx, chainId) {
  const typed = { domain: { chainId, verifyingContract: safe }, types: { EIP712Domain: [{ name: "chainId", type: "uint256" }, { name: "verifyingContract", type: "address" }], ...SAFE_TX_TYPES }, primaryType: "SafeTx", message: tx };
  return provider.send("eth_signTypedData_v4", [signer, JSON.stringify(typed)]);
}
const joinSigs = (pairs) => `0x${pairs.sort((a, b) => (BigInt(a[0]) < BigInt(b[0]) ? -1 : 1)).map(([, sig]) => sig.slice(2)).join("")}`;

async function guardLocalAnvil() {
  const u = new URL(URL_);
  if (!["127.0.0.1", "localhost"].includes(u.hostname)) throw new Error("Refusing: ANVIL_URL must be a local anvil node.");
  const client = await provider.send("web3_clientVersion", []);
  if (!/anvil/i.test(client)) throw new Error(`Refusing: endpoint is not anvil (${client}).`);
  return client;
}

async function main() {
  const client = await guardLocalAnvil();
  const forkBlock = await provider.getBlockNumber();
  const chainId = (await provider.getNetwork()).chainId.toString();
  const [o1, o2, o3, backup, buyer, wrong] = (await provider.send("eth_accounts", [])).slice(0, 6).map(getAddress);
  const old = getAddress(OLD_AUTHORITY);
  await provider.send("anvil_impersonateAccount", [old]);
  const out = { environment: `LOCAL ANVIL FORK of Fuji (chainId ${chainId}) at block ${forkBlock}; nothing broadcast to Fuji`, client, actors: { oldKey: `${old} (impersonated)`, testSafeOwners: [o1, o2, o3], testBackup: backup, buyer, note: "fork-only stand-ins, not proposed authorities" }, preSteps: [], safe: {}, p0: [], final: {}, failureCases: {} };
  out.failureCases.unresolvedSafeConfiguration = packageStatus(buildRotationPlan({ scope: "P0" }));

  // --- Pre-steps P-1/P-2: close the two open sales that pay the old key.
  const allEditionSlots = OPEN_OLD_KEY_SALES.map((e) => ({ tokenId: e.tokenId, slots: saleSlots(e.tokenId) }));
  const snapshotStorage = async () => Object.fromEntries(await Promise.all(allEditionSlots.flatMap(({ tokenId, slots }) => slots.map(async (s, i) => [`${tokenId.slice(0, 10)}+${i}`, await provider.getStorage(LEGACY_SALE_82B26, s)]))));
  const progress = (msg) => console.error(`[fork-rehearsal] ${msg}`);
  progress(`fork block ${forkBlock}; pre-steps`);
  for (const pre of buildSaleCloseSteps()) {
    const tokenId = pre.args.tokenId;
    const other = OPEN_OLD_KEY_SALES.find((e) => e.tokenId !== tokenId).tokenId;
    const before = saleIface.decodeFunctionResult("sales", await provider.call({ to: LEGACY_SALE_82B26, data: saleIface.encodeFunctionData("sales", [tokenId]) }));
    const payoutBefore = releaseEvents.decodeFunctionResult("payoutOf", await provider.call({ to: LEGACY_RELEASE_82B26, data: releaseEvents.encodeFunctionData("payoutOf", [tokenId]) }))[0];
    const purchaseBefore = await call(buyer, LEGACY_SALE_82B26, saleIface.encodeFunctionData("purchase", [tokenId, 1n]), before.priceWei);
    const storageBefore = await snapshotStorage();
    const tx = await send(old, pre.to, pre.calldata);
    const after = saleIface.decodeFunctionResult("sales", await provider.call({ to: LEGACY_SALE_82B26, data: saleIface.encodeFunctionData("sales", [tokenId]) }));
    const storageAfter = await snapshotStorage();
    const changedSlots = Object.keys(storageAfter).filter((k) => storageAfter[k] !== storageBefore[k]);
    const otherSale = saleIface.decodeFunctionResult("sales", await provider.call({ to: LEGACY_SALE_82B26, data: saleIface.encodeFunctionData("sales", [other]) }));
    out.preSteps.push({
      step: pre.step, tokenId, txStatus: tx.status, gasUsed: tx.gasUsed,
      saleConfiguredLog: tx.logs.map((l) => { try { const p = saleIface.parseLog(l); return p && { tokenId: p.args.tokenId.toString(), artist: p.args.artist, paused: p.args.paused, priceWei: p.args.priceWei.toString(), maxSupply: p.args.maxSupply.toString(), perWalletLimit: p.args.perWalletLimit.toString() }; } catch { return null; } }).filter(Boolean),
      unchangedFields: ["priceWei", "maxSupply", "sold", "perWalletLimit", "startTime", "endTime", "configured"].every((f) => before[f] === after[f]),
      pausedAfter: after.paused,
      changedSaleSlots: changedSlots,
      onlyPackedWordOfThisEditionChanged: changedSlots.length === 1 && changedSlots[0] === `${tokenId.slice(0, 10)}+4`,
      payoutUnchanged: releaseEvents.decodeFunctionResult("payoutOf", await provider.call({ to: LEGACY_RELEASE_82B26, data: releaseEvents.encodeFunctionData("payoutOf", [tokenId]) }))[0] === payoutBefore,
      purchaseBeforeClose: purchaseBefore.ok ? "OK" : purchaseBefore,
      purchaseAfterClose: await call(buyer, LEGACY_SALE_82B26, saleIface.encodeFunctionData("purchase", [tokenId, 1n]), before.priceWei),
      otherEdition: { tokenId: other, pausedAfterThisStep: otherSale.paused, expected: pre.step === "P-1" ? "false (untouched)" : "true (closed by P-1, untouched by P-2)" },
    });
  }

  progress("close failure cases");
  // Failure cases on the closes (each on a snapshot that is reverted afterwards).
  {
    const pre = buildSaleCloseSteps()[0];
    const base = await snapshotStorage();
    const id0 = await snapshot();
    const again = await send(old, pre.to, pre.calldata);
    const afterAgain = await snapshotStorage();
    out.failureCases.closeAlreadyClosedEdition = { txStatus: again.status, storageUnchanged: JSON.stringify(base) === JSON.stringify(afterAgain), note: "idempotent: re-sending a close changes nothing" };
    await revertTo(id0);
    const id1 = await snapshot();
    await send(old, LEGACY_RELEASE_82B26, releaseIface.encodeFunctionData("renounceRole", [ROLES.ARTIST_ROLE]));
    const reopen = saleIface.encodeFunctionData("configureSale", [pre.args.tokenId, pre.args.priceWei, pre.args.maxSupply, pre.args.perWalletLimit, pre.args.startTime, pre.args.endTime, true]);
    out.failureCases.closeAfterOldArtistRoleRemoved = await call(old, LEGACY_SALE_82B26, reopen);
    await revertTo(id1);
  }

  progress("test Safe creation");
  // --- Test Safe: 2-of-3 through the canonical factory and SafeL2 singleton.
  const initializer = safeIface.encodeFunctionData("setup", [[o1, o2, o3], 2, ZeroAddress, "0x", FALLBACK, ZeroAddress, 0, ZeroAddress]);
  const createData = factoryIface.encodeFunctionData("createProxyWithNonce", [SAFE_L2, initializer, BigInt(forkBlock)]);
  const predicted = getAddress(factoryIface.decodeFunctionResult("createProxyWithNonce", await provider.call({ from: o1, to: FACTORY, data: createData }))[0]);
  const created = await send(o1, FACTORY, createData);
  const safe = predicted;
  const read = async (fn) => safeIface.decodeFunctionResult(fn, await provider.call({ to: safe, data: safeIface.encodeFunctionData(fn) }))[0];
  out.safe = { address: safe, creationStatus: created.status, creationGas: created.gasUsed, version: await read("VERSION"), owners: (await read("getOwners")).map(getAddress), threshold: Number(await read("getThreshold")), nonce: (await read("nonce")).toString() };

  // --- P0 package exactly as generated for this Safe/backup.
  const plan = buildRotationPlan({ safe, backup, safeNonce: Number(out.safe.nonce), scope: "P0" });
  out.p0PackageStatus = packageStatus(plan).status;
  const signers = [o1, o2].sort((a, b) => (BigInt(a) < BigInt(b) ? -1 : 1));
  const adminRemoval = plan.find((st) => st.safeTx && st.args.role === "DEFAULT_ADMIN_ROLE");
  const execData = (t, signatures) => safeIface.encodeFunctionData("execTransaction", [t.to, t.value, t.data, t.operation, t.safeTxGas, t.baseGas, t.gasPrice, t.gasToken, t.refundReceiver, signatures]);
  {
    // Wrong address granted by mistake: recoverable by the old key while it is still admin.
    const id2 = await snapshot();
    await send(old, P0_RELEASE, releaseIface.encodeFunctionData("grantRole", [ROLES.DEFAULT_ADMIN_ROLE, wrong]));
    const granted = await hasRole(P0_RELEASE, "DEFAULT_ADMIN_ROLE", wrong);
    await send(old, P0_RELEASE, releaseIface.encodeFunctionData("revokeRole", [ROLES.DEFAULT_ADMIN_ROLE, wrong]));
    out.failureCases.wrongAddressGrantRecovery = { grantedByMistake: granted, revokedByOldKey: !(await hasRole(P0_RELEASE, "DEFAULT_ADMIN_ROLE", wrong)) };
    await revertTo(id2);
    // Compromised-key race: between the grant and the Safe's removal, the old key can revoke the Safe.
    const id3 = await snapshot();
    await send(old, P0_RELEASE, plan[0].calldata);
    await send(old, P0_RELEASE, releaseIface.encodeFunctionData("revokeRole", [ROLES.DEFAULT_ADMIN_ROLE, safe]));
    const t = adminRemoval.safeTx;
    const sigs = [];
    for (const sgn of signers) sigs.push([sgn, await signSafeTx(sgn, safe, t, Number(chainId))]);
    const attempt = await call(buyer, safe, execData(t, joinSigs(sigs)));
    out.failureCases.compromisedOldKeyRace = { oldKeyRevokedSafeAfterGrant: !(await hasRole(P0_RELEASE, "DEFAULT_ADMIN_ROLE", safe)), safeRemovalOfOldAdminThenFails: !attempt.ok, revert: attempt.revertData, note: "the race is real: until the Safe's removal executes, the old key can undo the grant" };
    await revertTo(id3);
  }
  progress("P0 package");
  for (const step of plan) {
    progress(`P0 step ${step.step} ${step.phase}`);
    const entry = { step: step.step, phase: step.phase, function: step.function, args: step.args };
    if (step.safeTx) {
      const t = step.safeTx;
      const liveHash = safeIface.decodeFunctionResult("getTransactionHash", await provider.call({ to: safe, data: safeIface.encodeFunctionData("getTransactionHash", [t.to, t.value, t.data, t.operation, t.safeTxGas, t.baseGas, t.gasPrice, t.gasToken, t.refundReceiver, t.nonce]) }))[0];
      entry.safeTxHash = { package: step.safeTxHash, safeContract: liveHash, match: liveHash === step.safeTxHash };
      const typed = { domain: { chainId: Number(chainId), verifyingContract: safe }, types: { EIP712Domain: [{ name: "chainId", type: "uint256" }, { name: "verifyingContract", type: "address" }], ...SAFE_TX_TYPES }, primaryType: "SafeTx", message: t };
      const sigs = [];
      for (const s of signers) sigs.push(await provider.send("eth_signTypedData_v4", [s, JSON.stringify(typed)]));
      const exec = (signatures) => safeIface.encodeFunctionData("execTransaction", [t.to, t.value, t.data, t.operation, t.safeTxGas, t.baseGas, t.gasPrice, t.gasToken, t.refundReceiver, signatures]);
      entry.oneSignatureRejected = !(await call(buyer, safe, exec(sigs[0]))).ok;
      if (step === adminRemoval) {
        const wrongChain = [];
        for (const sgn of signers) wrongChain.push([sgn, await signSafeTx(sgn, safe, t, 43114)]);
        out.failureCases.safeSignaturesForWrongChainRejected = !(await call(buyer, safe, exec(joinSigs(wrongChain)))).ok;
        const nonOwner = [[signers[0], sigs[0]], [backup, await signSafeTx(backup, safe, t, Number(chainId))]];
        out.failureCases.nonOwnerSignatureRejected = !(await call(buyer, safe, exec(joinSigs(nonOwner)))).ok;
        out.failureCases.safeRemovalWithoutBackupGrantWouldStillLeaveSafeAdmin = "n/a: the generator always grants and proves the backup first (unit-tested)";
      }
      const tx = await send(buyer, safe, exec(`0x${sigs.map((x) => x.slice(2)).join("")}`));
      Object.assign(entry, { executedBy: `${buyer} (any account may submit once ${out.safe.threshold} owner signatures exist)`, txStatus: tx.status, gasUsed: tx.gasUsed, roleEvents: roleLogs(tx.logs) });
    } else {
      const from = step.signer;
      const tx = await send(from, step.to, step.calldata);
      Object.assign(entry, { from, txStatus: tx.status, gasUsed: tx.gasUsed, roleEvents: roleLogs(tx.logs) });
    }
    entry.after = {};
    for (const [who, a] of Object.entries({ old, safe, backup })) entry.after[who] = Object.fromEntries(await Promise.all(Object.keys(ROLES).map(async (r) => [r, await hasRole(P0_RELEASE, r, a)])));
    out.p0.push(entry);
  }
  out.final = {
    oldCanAdminister: (await call(old, P0_RELEASE, releaseIface.encodeFunctionData("grantRole", [ROLES.DEFAULT_ADMIN_ROLE, old]))).ok,
    oldCanMint: (await call(old, P0_RELEASE, releaseEvents.encodeFunctionData("mint", [old, 1n, 1n, "0x"]))).ok,
    safeCanAdminister: (await call(safe, P0_RELEASE, releaseIface.encodeFunctionData("grantRole", [ROLES.DEFAULT_ADMIN_ROLE, safe]))).ok,
    backupCanAdminister: (await call(backup, P0_RELEASE, releaseIface.encodeFunctionData("grantRole", [ROLES.DEFAULT_ADMIN_ROLE, backup]))).ok,
    p1ArtistRevokeOn0x82b26AfterPreSteps: "not executed here (P1 is out of P0 scope)",
  };
  console.log(JSON.stringify(out, null, 2));
}

main().catch((error) => { console.error(error); process.exit(1); });
